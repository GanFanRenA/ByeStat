  function normalizeLocale(locale) {
    return String(locale ?? "")
      .toLowerCase()
      .startsWith("en")
      ? "en"
      : "zh";
  }

  function translate(locale, key, parameters = {}) {
    const language = normalizeLocale(locale);
    const template = messages[language][key] ?? messages.zh[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (match, name) =>
      Object.prototype.hasOwnProperty.call(parameters, name)
        ? String(parameters[name])
        : match,
    );
  }

  function languageTag(locale) {
    return normalizeLocale(locale) === "en" ? "en" : "zh-CN";
  }

  ByeStat.i18n = { languageTag, normalizeLocale, translate };
